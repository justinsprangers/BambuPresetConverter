# Snapshots Bambu Studio's system filament presets into profiles.js for the converter page.
# Rerun after every Bambu Studio update:  powershell -ExecutionPolicy Bypass -File update-profiles.ps1
param([string]$BambuDir = "C:\Program Files\Bambu Studio\resources\profiles\BBL")

$ErrorActionPreference = 'Stop'
$filDir = Join-Path $BambuDir 'filament'
if (-not (Test-Path $filDir)) { throw "Bambu Studio profiles not found at $filDir. Pass -BambuDir <path to resources\profiles\BBL>." }

Write-Host "Reading $filDir ..."
$byName = @{}
foreach ($f in Get-ChildItem $filDir -Recurse -Filter *.json) {
    $j = Get-Content $f.FullName -Raw -Encoding UTF8 | ConvertFrom-Json
    if ($j.name) { $byName[$j.name] = $j }
}

# Parents in lookup order: includes (templates) first, then inherits.
function Get-Chain($p) {
    $chain = New-Object System.Collections.ArrayList
    $queue = New-Object System.Collections.Queue
    $queue.Enqueue($p)
    while ($queue.Count) {
        $x = $queue.Dequeue()
        if ($chain.Contains($x)) { continue }
        [void]$chain.Add($x)
        foreach ($inc in @($x.include)) { if ($inc -and $byName[$inc]) { $queue.Enqueue($byName[$inc]) } }
        if ($x.inherits -and $byName[$x.inherits]) { $queue.Enqueue($byName[$x.inherits]) }
    }
    return $chain
}

function Resolve-Key($chain, $key) {
    foreach ($x in $chain) { $prop = $x.PSObject.Properties[$key]; if ($prop) { return ,@($prop.Value) } }
    return $null
}

$keysets = New-Object System.Collections.ArrayList
$keysetIndex = @{}
$out = New-Object System.Collections.ArrayList

foreach ($p in $byName.Values) {
    if ($p.instantiation -ne 'true' -or -not $p.compatible_printers) { continue }
    $chain = Get-Chain $p
    $variants = Resolve-Key $chain 'filament_extruder_variant'
    $entry = [ordered]@{ n = $p.name; c = @($p.compatible_printers) }
    if ($variants -and $variants.Count -gt 1) {
        $entry.v = @($variants)
        # Keys that hold one value per extruder variant.
        $names = @{}
        foreach ($x in $chain) { foreach ($prop in $x.PSObject.Properties) { $names[$prop.Name] = 1 } }
        $vk = @($names.Keys | Where-Object { $v = Resolve-Key $chain $_; $v -and $v.Count -eq $variants.Count } | Sort-Object)
        $sig = $vk -join ','
        if (-not $keysetIndex.ContainsKey($sig)) { $keysetIndex[$sig] = $keysets.Count; [void]$keysets.Add($vk) }
        $entry.k = $keysetIndex[$sig]
    }
    [void]$out.Add($entry)
}

$bblJson = Join-Path (Split-Path $BambuDir) 'BBL.json'
$ver = if (Test-Path $bblJson) { (Get-Content $bblJson -Raw | ConvertFrom-Json).version } else { 'unknown' }
$data = [ordered]@{ generated = (Get-Date -Format 'yyyy-MM-dd'); bambuProfileVersion = $ver; keysets = $keysets.ToArray(); filaments = $out.ToArray() }
$js = "// Generated by update-profiles.ps1 from Bambu Studio's system presets. Do not edit by hand.`nwindow.BAMBU_PROFILES = " + ($data | ConvertTo-Json -Depth 6 -Compress) + ";`n"
$dest = Join-Path $PSScriptRoot 'profiles.js'
[IO.File]::WriteAllText($dest, $js, (New-Object Text.UTF8Encoding $false))
Write-Host "Wrote $($out.Count) system filament presets (profile version $ver) to $dest"
