# Snapshots Bambu Studio's system filament and process presets into profiles.js for the converter page.
# Rerun after every Bambu Studio update:  powershell -ExecutionPolicy Bypass -File update-profiles.ps1
param([string]$BambuDir = "C:\Program Files\Bambu Studio\resources\profiles\BBL")

$ErrorActionPreference = 'Stop'
if (-not (Test-Path (Join-Path $BambuDir 'filament'))) { throw "Bambu Studio profiles not found in $BambuDir. Pass -BambuDir <path to resources\profiles\BBL>." }

# Parents in lookup order: the preset, its includes (templates), then what it inherits.
function Get-Chain($p, $byName) {
    $chain = New-Object System.Collections.ArrayList
    $queue = New-Object System.Collections.Queue
    $queue.Enqueue($p)
    while ($queue.Count) {
        $x = $queue.Dequeue()
        if ($chain.Contains($x)) { continue }
        [void]$chain.Add($x)
        foreach ($inc in @($x.include)) { if ($inc -and $byName[$inc]) { $queue.Enqueue($byName[$inc]) } }
        if ($x.inherits -and $byName[$x.inherits]) { $queue.Enqueue($byName[$x.inherits]) }
    }
    return $chain
}

function Resolve-Key($chain, $key) {
    foreach ($x in $chain) { $prop = $x.PSObject.Properties[$key]; if ($prop) { return ,@($prop.Value) } }
    return $null
}

$keysets = New-Object System.Collections.ArrayList
$keysetIndex = @{}

# variantField: the key listing extruder variants ("filament_extruder_variant" / "print_extruder_variant").
function Read-Folder($folder, $variantField) {
    $dir = Join-Path $BambuDir $folder
    Write-Host "Reading $dir ..."
    $byName = @{}
    foreach ($f in Get-ChildItem $dir -Recurse -Filter *.json) {
        $j = Get-Content $f.FullName -Raw -Encoding UTF8 | ConvertFrom-Json
        if ($j.name) { $byName[$j.name] = $j }
    }
    $out = New-Object System.Collections.ArrayList
    foreach ($p in $byName.Values) {
        if ($p.instantiation -ne 'true' -or -not $p.compatible_printers) { continue }
        $chain = Get-Chain $p $byName
        $variants = Resolve-Key $chain $variantField
        $entry = [ordered]@{ n = $p.name; c = @($p.compatible_printers) }
        if ($variants -and $variants.Count -gt 1) {
            $entry.v = @($variants)
            # Keys holding one value per extruder variant, with the base's values (to tell edits from defaults).
            $names = @{}
            foreach ($x in $chain) { foreach ($prop in $x.PSObject.Properties) { $names[$prop.Name] = 1 } }
            $defaults = [ordered]@{}
            foreach ($k in ($names.Keys | Sort-Object)) {
                if ($k -eq $variantField) { continue }
                $v = Resolve-Key $chain $k
                if ($v -and $v.Count -eq $variants.Count) { $defaults[$k] = @($v | ForEach-Object { [string]$_ }) }
            }
            $sig = @($defaults.Keys) -join ','
            if (-not $keysetIndex.ContainsKey($sig)) { $keysetIndex[$sig] = $keysets.Count; [void]$keysets.Add(@($defaults.Keys)) }
            $entry.k = $keysetIndex[$sig]
            $entry.d = @($defaults.Values | ForEach-Object { ,@($_) })
        }
        [void]$out.Add($entry)
    }
    return ,$out.ToArray()
}

$filaments = Read-Folder 'filament' 'filament_extruder_variant'
$processes = Read-Folder 'process' 'print_extruder_variant'

$bblJson = Join-Path (Split-Path $BambuDir) 'BBL.json'
$ver = if (Test-Path $bblJson) { (Get-Content $bblJson -Raw | ConvertFrom-Json).version } else { 'unknown' }
$data = [ordered]@{ generated = (Get-Date -Format 'yyyy-MM-dd'); bambuProfileVersion = $ver; keysets = $keysets.ToArray();
    filaments = $filaments; processes = $processes }
$js = "// Generated by update-profiles.ps1 from Bambu Studio's system presets. Do not edit by hand.`nwindow.BAMBU_PROFILES = " + ($data | ConvertTo-Json -Depth 8 -Compress) + ";`n"
$dest = Join-Path $PSScriptRoot 'profiles.js'
[IO.File]::WriteAllText($dest, $js, (New-Object Text.UTF8Encoding $false))
Write-Host "Wrote $($filaments.Count) filament and $($processes.Count) process presets (profile version $ver) to $dest"
